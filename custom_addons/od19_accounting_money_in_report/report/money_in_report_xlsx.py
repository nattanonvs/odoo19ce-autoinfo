import base64
import io
from datetime import datetime

from odoo import models

try:
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill
except ImportError:
    openpyxl = None


class MoneyInReportXlsx(models.AbstractModel):
    _name = "report.od19_accounting_money_in_report.money_in_report_xlsx"
    _description = "Money In Report XLSX"

    def _get_report_data(self, runs):
        """Return summary and detail rows for the given report runs."""
        summary_rows = []
        detail_rows = []
        for run in runs:
            summary_rows.append(
                {
                    "name": run.name,
                    "company": run.company_id.name or "",
                    "date_from": run.date_from or "",
                    "date_to": run.date_to or "",
                    "phase": dict(
                        run._fields["phase"].selection
                    ).get(run.phase, run.phase),
                    "status": dict(
                        run._fields["status"].selection
                    ).get(run.status, run.status),
                    "generated_by": run.generated_by_id.name or "",
                    "generated_at": run.generated_at or "",
                    "line_count": run.line_count,
                }
            )
            for line in run.line_ids:
                detail_rows.append(
                    {
                        "run_name": run.name,
                        "partner": line.partner_id.name or "",
                        "salesperson": line.salesperson_id.name or "",
                        "project": line.project_id.name or "",
                        "project_job_type": line.project_job_type or "",
                        "product": line.product_id.name or "",
                        "product_category": line.product_categ_id.name or "",
                        "invoice": line.invoice_id.name or "",
                        "invoice_date": line.invoice_date or "",
                        "stamp_date": line.stamp_date or "",
                        "customer_reference": line.customer_reference or "",
                        "sale_order": line.sale_order_id.name or "",
                        "recognition_mode": dict(
                            line._fields["recognition_mode"].selection
                        ).get(line.recognition_mode, line.recognition_mode),
                        "recognized_amount": line.recognized_amount or 0.0,
                        "sale_order_amount": line.sale_order_amount or 0.0,
                        "paid_amount": line.paid_amount or 0.0,
                        "refund_amount": line.refund_amount or 0.0,
                        "net_cash_amount": line.net_cash_amount or 0.0,
                        "recognized_cost": line.recognized_cost or 0.0,
                        "recognized_profit": line.recognized_profit or 0.0,
                        "recognized_margin_pct": line.recognized_margin_pct or 0.0,
                        "cost_preliminary_available": "Yes"
                        if line.cost_preliminary_available
                        else "No",
                        "profit_preliminary_available": "Yes"
                        if line.profit_preliminary_available
                        else "No",
                        "cycle_start_date": line.cycle_start_date or "",
                        "cycle_end_date": line.cycle_end_date or "",
                        "cycle_days": line.cycle_days or 0,
                        "payment_date": line.payment_date or "",
                        "reconcile_date": line.reconcile_date or "",
                    }
                )
        return summary_rows, detail_rows

    def create_xlsx_report(self, docids, data):
        """Generate the XLSX report and return a base64-encoded string."""
        if openpyxl is None:
            raise RuntimeError("openpyxl is not installed")

        runs = self.env["od19.money.in.report.run"].browse(docids)
        summary_rows, detail_rows = self._get_report_data(runs)

        workbook = openpyxl.Workbook()

        # --- Summary sheet ---
        summary_sheet = workbook.active
        summary_sheet.title = "Summary"
        summary_headers = [
            "Run Name",
            "Company",
            "Date From",
            "Date To",
            "Phase",
            "Status",
            "Generated By",
            "Generated At",
            "Line Count",
        ]
        self._write_sheet(summary_sheet, summary_headers, summary_rows)

        # --- Detail sheet ---
        detail_sheet = workbook.create_sheet(title="Detail Lines")
        detail_headers = [
            "Run",
            "Partner",
            "Salesperson",
            "Project",
            "Job Type",
            "Product",
            "Product Category",
            "Invoice",
            "Invoice Date",
            "Stamp Date",
            "Customer Ref",
            "Sale Order",
            "Recognition Mode",
            "Recognized Amount",
            "SO Amount",
            "Paid Amount",
            "Refund Amount",
            "Net Cash Amount",
            "Recognized Cost",
            "Recognized Profit",
            "Margin %",
            "Cost Available",
            "Profit Available",
            "Cycle Start",
            "Cycle End",
            "Cycle Days",
            "Payment Date",
            "Reconcile Date",
        ]
        self._write_sheet(detail_sheet, detail_headers, detail_rows)

        # Save to in-memory buffer
        buffer = io.BytesIO()
        workbook.save(buffer)
        buffer.seek(0)
        return base64.b64encode(buffer.read())

    def _write_sheet(self, sheet, headers, rows):
        """Write headers and rows to a worksheet with basic formatting."""
        header_font = Font(bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="4F81BD", end_color="4F81BD", fill_type="solid")
        header_alignment = Alignment(horizontal="center", vertical="center")

        for col_idx, header in enumerate(headers, start=1):
            cell = sheet.cell(row=1, column=col_idx, value=header)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = header_alignment

        for row_idx, row in enumerate(rows, start=2):
            for col_idx, header in enumerate(headers, start=1):
                key = self._header_to_key(header)
                value = row.get(key, "")
                sheet.cell(row=row_idx, column=col_idx, value=value)

        # Auto-size columns
        for col_idx in range(1, len(headers) + 1):
            max_length = len(str(headers[col_idx - 1]))
            for row_idx in range(2, len(rows) + 2):
                cell_value = sheet.cell(row=row_idx, column=col_idx).value
                if cell_value is not None:
                    max_length = max(max_length, len(str(cell_value)))
            sheet.column_dimensions[
                openpyxl.utils.get_column_letter(col_idx)
            ].width = min(max_length + 2, 40)

    @staticmethod
    def _header_to_key(header):
        """Map a display header to the corresponding row dict key."""
        mapping = {
            "Run Name": "name",
            "Company": "company",
            "Date From": "date_from",
            "Date To": "date_to",
            "Phase": "phase",
            "Status": "status",
            "Generated By": "generated_by",
            "Generated At": "generated_at",
            "Line Count": "line_count",
            "Run": "run_name",
            "Partner": "partner",
            "Salesperson": "salesperson",
            "Project": "project",
            "Job Type": "project_job_type",
            "Product": "product",
            "Product Category": "product_category",
            "Invoice": "invoice",
            "Invoice Date": "invoice_date",
            "Stamp Date": "stamp_date",
            "Customer Ref": "customer_reference",
            "Sale Order": "sale_order",
            "Recognition Mode": "recognition_mode",
            "Recognized Amount": "recognized_amount",
            "SO Amount": "sale_order_amount",
            "Paid Amount": "paid_amount",
            "Refund Amount": "refund_amount",
            "Net Cash Amount": "net_cash_amount",
            "Recognized Cost": "recognized_cost",
            "Recognized Profit": "recognized_profit",
            "Margin %": "recognized_margin_pct",
            "Cost Available": "cost_preliminary_available",
            "Profit Available": "profit_preliminary_available",
            "Cycle Start": "cycle_start_date",
            "Cycle End": "cycle_end_date",
            "Cycle Days": "cycle_days",
            "Payment Date": "payment_date",
            "Reconcile Date": "reconcile_date",
        }
        return mapping.get(header, header.lower().replace(" ", "_"))
